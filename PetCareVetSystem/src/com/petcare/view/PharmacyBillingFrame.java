    // 3. Bill Total Calculate කිරීම
    private void calculateTotal() {
        DefaultTableModel model = (DefaultTableModel) tblPharmacyItems.getModel();
        currentMedicineTotal = 0.0;

        for (int i = 0; i < model.getRowCount(); i++) {
            double price = Double.parseDouble(model.getValueAt(i, 4).toString());
            int qty = Integer.parseInt(model.getValueAt(i, 3).toString());
            double sub = price * qty;
            model.setValueAt(sub, i, 5); // Sub Total Update කිරීම
            currentMedicineTotal += sub;
        }

        lblNetTotal.setText("Medicine Total: Rs. " + String.format("%.2f", currentMedicineTotal));
    }
    
    
