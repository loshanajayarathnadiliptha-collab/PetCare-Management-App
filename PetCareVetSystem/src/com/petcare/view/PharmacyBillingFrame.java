    private void cmbPharmacyQueueActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbPharmacyQueueActionPerformed
        // TODO add your handling code here:
        int index = cmbPharmacyQueue.getSelectedIndex();
        if (index == -1) return;

        int prescId = prescriptionIds.get(index);
        DefaultTableModel model = (DefaultTableModel) tblPharmacyItems.getModel();
        model.setRowCount(0);

        String sql = "SELECT pi.item_id, m.medicine_name, pi.dosage, pi.quantity, m.selling_price " +
                     "FROM prescription_items pi " +
                     "JOIN medicines m ON pi.medicine_id = m.medicine_id " +
                     "WHERE pi.prescription_id = ?";

        try {
            Connection conn = DBConnection.getInstance().getConnection();
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setInt(1, prescId);
            ResultSet rs = pst.executeQuery();

            while (rs.next()) {
                double price = rs.getDouble("selling_price");
                int qty = rs.getInt("quantity");
                double subTotal = price * qty;

                model.addRow(new Object[]{
                    rs.getInt("item_id"),
                    rs.getString("medicine_name"),
                    rs.getString("dosage"),
                    qty,
                    price,
                    subTotal
                });
            }
            calculateTotal();
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }//GEN-LAST:event_cmbPharmacyQueueActionPerformed

