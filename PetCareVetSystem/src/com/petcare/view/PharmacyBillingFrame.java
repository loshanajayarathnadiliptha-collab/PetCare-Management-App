    // 1. Pharmacy-Pending Appointments Load කිරීම
    private void loadPharmacyQueue() {
        cmbPharmacyQueue.removeAllItems();
        appointmentIds.clear();
        prescriptionIds.clear();

        String sql = "SELECT a.appointment_id, p.prescription_id, pt.pet_name, c.name AS owner_name, p.treatment_note " +
                     "FROM appointments a " +
                     "JOIN prescriptions p ON a.appointment_id = p.appointment_id " +
                     "JOIN pets pt ON a.pet_id = pt.pet_id " +
                     "JOIN customers c ON pt.customer_id = c.customer_id " +
                     "WHERE a.status = 'Pharmacy-Pending'";

        try {
            Connection conn = DBConnection.getInstance().getConnection();
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery(sql);

            while (rs.next()) {
                int apptId = rs.getInt("appointment_id");
                int prescId = rs.getInt("prescription_id");
                String pet = rs.getString("pet_name");
                String owner = rs.getString("owner_name");

                appointmentIds.add(apptId);
                prescriptionIds.add(prescId);
                cmbPharmacyQueue.addItem("Appt #" + apptId + " - Pet: " + pet + " (" + owner + ")");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading pharmacy queue: " + ex.getMessage());
        }
    }
    

