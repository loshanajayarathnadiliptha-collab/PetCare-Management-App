    private void btnCompleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompleteActionPerformed
        // TODO add your handling code here:
        
        int index = cmbPharmacyQueue.getSelectedIndex();
        if (index == -1) {
            JOptionPane.showMessageDialog(this, "Please Select An Appointment!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int apptId = appointmentIds.get(index);
        calculateTotal();

        String sql = "UPDATE appointments SET status = 'Payment-Pending' WHERE appointment_id = ?";

        try {
            Connection conn = DBConnection.getInstance().getConnection();
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setInt(1, apptId);

            if (pst.executeUpdate() > 0) {
                JOptionPane.showMessageDialog(this, "Pharmacy Order Completed!\nSent to Reception for Payment.");
                loadPharmacyQueue(); // Table & Combo refresh
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error completing order: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnCompleteActionPerformed

