    // 3. Net Total Calculate කිරීම
    private void calculateNetTotal() {
        try {
            String scText = txtServiceCharge.getText().trim();
            serviceCharge = scText.isEmpty() ? 0.0 : Double.parseDouble(scText);
        } catch (Exception e) {
            serviceCharge = 0.0;
        }

        netTotal = doctorFee + pharmacyFee + serviceCharge;
        lblNetTotal.setText("Net Total: Rs. " + String.format("%.2f", netTotal));
    }

