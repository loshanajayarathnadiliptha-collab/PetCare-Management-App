    private void btnCompletePaymentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompletePaymentActionPerformed
        // TODO add your handling code here:
        
        int index = cmbPaymentQueue.getSelectedIndex();
        if (index == -1) {
            JOptionPane.showMessageDialog(this, "Please Select An Appointment !", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int apptId = appointmentIds.get(index);
        calculateNetTotal();
        String paymentMethod = cmbPaymentMethod.getSelectedItem().toString();

        Connection conn = null;
        try {
            conn = DBConnection.getInstance().getConnection();
            conn.setAutoCommit(false); // Transaction processing

            // A. Invoices Table  Record  Insert 
            String sqlInvoice = "INSERT INTO invoices (appointment_id, doctor_fee, service_charge, medicine_total, net_total, payment_method) VALUES (?, ?, ?, ?, ?, ?)";
            PreparedStatement pst1 = conn.prepareStatement(sqlInvoice);
            pst1.setInt(1, apptId);
            pst1.setDouble(2, doctorFee);
            pst1.setDouble(3, serviceCharge);
            pst1.setDouble(4, pharmacyFee);
            pst1.setDouble(5, netTotal);
            pst1.setString(6, paymentMethod);
            pst1.executeUpdate();

            // B. Appointment Status to convert 'Completed'
            String sqlUpdateAppt = "UPDATE appointments SET status = 'Completed' WHERE appointment_id = ?";
            PreparedStatement pst2 = conn.prepareStatement(sqlUpdateAppt);
            pst2.setInt(1, apptId);
            pst2.executeUpdate();

            conn.commit(); // Save transaction

            JOptionPane.showMessageDialog(this, "Payment Complete!\nInvoice Saved Successfully.");
            
            // Clear & Refresh
            txtServiceCharge.setText("");
            lblDoctorFee.setText("Doctor Fee: Rs. 0.00");
            lblPharmacyFee.setText("Pharmacy Fee: Rs. 0.00");
            lblNetTotal.setText("Net Total: Rs. 0.00");
            loadPaymentQueue();

        } catch (Exception ex) {
            try { if (conn != null) conn.rollback(); } catch (Exception e) {}
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Payment Processing Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCompletePaymentActionPerformed

