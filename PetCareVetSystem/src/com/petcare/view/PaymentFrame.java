    // 1. Payment-Pending Status තියෙන Appointments Combo Box එකට Load කිරීම
    private void loadPaymentQueue() {
        cmbPaymentQueue.removeAllItems();
        appointmentIds.clear();

        String sql = "SELECT a.appointment_id, pt.pet_name, c.name AS owner_name " +
                     "FROM appointments a " +
                     "JOIN pets pt ON a.pet_id = pt.pet_id " +
                     "JOIN customers c ON pt.customer_id = c.customer_id " +
                     "WHERE a.status = 'Payment-Pending'";

        try {
            Connection conn = DBConnection.getInstance().getConnection();
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery(sql);

            while (rs.next()) {
                int apptId = rs.getInt("appointment_id");
                String pet = rs.getString("pet_name");
                String owner = rs.getString("owner_name");

                appointmentIds.add(apptId);
                cmbPaymentQueue.addItem("Appt #" + apptId + " - Pet: " + pet + " (" + owner + ")");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Payment Queue Load Error: " + ex.getMessage());
        }
     }

