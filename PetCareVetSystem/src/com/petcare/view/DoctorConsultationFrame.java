    // 1. Pending/In-Consultation Appointments Combo එකට Load කිරීම
    private void loadPendingAppointments() {
        cmbAppointments.removeAllItems();
        appointmentIds.clear();

        String sql = "SELECT a.appointment_id, p.pet_name, c.name AS owner_name " +
                     "FROM appointments a " +
                     "JOIN pets p ON a.pet_id = p.pet_id " +
                     "JOIN customers c ON p.customer_id = c.customer_id " +
                     "WHERE a.status IN ('Pending', 'In-Consultation')";

        try {
            Connection conn = DBConnection.getInstance().getConnection();
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery(sql);

            while (rs.next()) {
                int id = rs.getInt("appointment_id");
                String pet = rs.getString("pet_name");
                String owner = rs.getString("owner_name");

                appointmentIds.add(id);
                cmbAppointments.addItem("Appt #" + id + " - Pet: " + pet + " (Owner: " + owner + ")");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

    // 2. Simple/Capital ඕනෑම විදිහට Type කරද්දී Case-Insensitive Medicine Search වීම
    private void setupMedicineAutoSearch() {
        txtMedSearch.getDocument().addDocumentListener(new DocumentListener() {
            public void insertUpdate(DocumentEvent e) { searchMedicines(); }
            public void removeUpdate(DocumentEvent e) { searchMedicines(); }
            public void changedUpdate(DocumentEvent e) { searchMedicines(); }
        });
    }

    private void searchMedicines() {
        String searchText = txtMedSearch.getText().trim().toLowerCase();
        cmbMedicines.removeAllItems();
        medicineIds.clear();

        if (searchText.isEmpty()) return;

        // LOWER() පාවිච්චි කර සිම්පල්/කැපිටල් දෙකටම ගැලපෙන සේ Search කිරීම
        String sql = "SELECT medicine_id, medicine_name, category FROM medicines WHERE LOWER(medicine_name) LIKE ?";

        try {
            Connection conn = DBConnection.getInstance().getConnection();
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, "%" + searchText + "%");
            ResultSet rs = pst.executeQuery();

            while (rs.next()) {
                medicineIds.add(rs.getInt("medicine_id"));
                cmbMedicines.addItem(rs.getString("medicine_name") + " (" + rs.getString("category") + ")");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }
    

