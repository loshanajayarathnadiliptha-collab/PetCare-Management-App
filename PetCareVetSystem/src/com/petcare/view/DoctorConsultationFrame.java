    private void btnAddMedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddMedActionPerformed
        // TODO add your handling code here:
        
        if (cmbMedicines.getSelectedIndex() == -1) {
            JOptionPane.showMessageDialog(this, "Please Select Medicine !", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int medId = medicineIds.get(cmbMedicines.getSelectedIndex());
        String medName = cmbMedicines.getSelectedItem().toString();
        String dosage = txtDosage.getText().trim();
        String type = txtType.getText().trim();
        int qty = Integer.parseInt(spnQty.getValue().toString());

        if (dosage.isEmpty() || qty <= 0) {
            JOptionPane.showMessageDialog(this, "Enter The Dosage And valid Quantity!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tblPrescription.getModel();
        model.addRow(new Object[]{medId, medName, type, dosage, qty});

        txtDosage.setText("");
        txtType.setText("");
        spnQty.setValue(1);
    }//GEN-LAST:event_btnAddMedActionPerformed

